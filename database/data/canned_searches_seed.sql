-- Seed the canned_searches catalog: 600 example searches for the Discover pills.
--
-- Run with: psql -d <database> -f database/data/canned_searches_seed.sql
-- (or let `npm run db:reset` do it, via setup_data.sql).
--
-- Idempotent. ON CONFLICT (query) DO NOTHING means re-running after adding rows
-- below inserts only the new ones and leaves every existing id alone, which
-- matters because user_pinned_searches references them.
--
-- These are written the way a person describes what they are in the mood for,
-- not the way anyone types into a keyword box -- the pills land on /search,
-- which is LLM-backed (POST /ai/search). "books for an intelligent layman on
-- evolution", not "evolution nonfiction".
--
-- Fifteen subjects of forty. The row draws one pill per subject (see
-- getRandomActive in data/canned-searches-data.ts), so a category here is a
-- variety guarantee, not a label: six pills means six different subjects, never
-- three shades of the same one. Two consequences when editing:
--
--   * Keep the categories balanced. A subject with ten rows is drawn from as
--     often as one with a hundred, so its ten queries turn up six times as
--     often as they should.
--   * Adding a sixteenth subject widens the row's range for free; adding forty
--     more rows to an existing one does not.
--
-- No apostrophes anywhere in the text below, deliberately -- it keeps this file
-- free of doubled quotes and easy to extend by hand.

